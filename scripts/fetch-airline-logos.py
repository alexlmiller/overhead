#!/usr/bin/env python3
"""Bundle airline logos and designators from data/airlines.txt into web/.

Logos are ICAO-named marks from github.com/Jxck-S/airline-logos, pinned to one
commit: FlightAware's 90 px set first, then RadarBox and the repository's custom
marks. They remain their owners' trademarks and are bundled only to identify
flights on this display. Also writes web/airlines.mjs: the logos the page
may request, and IATA designators for readable flight numbers ("UA 696").
--offline keeps the bundled logos and only regenerates web/airlines.mjs.
"""
import json
import pathlib
import re
import struct
import sys
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
LIST = ROOT/"data/airlines.txt"
LOGOS = ROOT/"web/logos"
MODULE = ROOT/"web/airlines.mjs"
COMMIT = "e0b218991caef4832e0db911136173e8eead942a"
SOURCES = ("flightaware_logos", "radarbox_logos", "custom_logos")
MAX_BYTES, MAX_SIDE = 32*1024, 256


def load_airlines(path=LIST):
    """ICAO code -> IATA designator ("" when callsigns stay as broadcast)."""
    airlines = {}
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split()
        if (len(fields) < 3 or not re.fullmatch(r"[A-Z]{3}", fields[0]) or fields[0] in airlines
                or not re.fullmatch(r"[A-Z0-9]{2}|-", fields[1])):
            raise ValueError(f"{path.name}:{number}: expected a unique ICAO code, an IATA designator or -, and a name")
        airlines[fields[0]] = "" if fields[1] == "-" else fields[1]
    return airlines


def png_size(data):
    """Width and height of a PNG, or None when the bytes are not one."""
    if len(data) < 24 or data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        return None
    return struct.unpack(">II", data[16:24])


def usable(data):
    size = png_size(data)
    return size is not None and len(data) <= MAX_BYTES and all(0 < side <= MAX_SIDE for side in size)


def fetch(code):
    for source in SOURCES:
        url = f"https://raw.githubusercontent.com/Jxck-S/airline-logos/{COMMIT}/{source}/{code}.png"
        try:
            with urllib.request.urlopen(url, timeout=20) as response:
                data = response.read(MAX_BYTES+1)
        except urllib.error.HTTPError as error:
            if error.code == 404:
                continue
            raise
        if usable(data):
            return data
    return None


def render(logos, airlines):
    designators = {code: iata for code, iata in sorted(airlines.items()) if iata}
    return ("// Generated by scripts/fetch-airline-logos.py from data/airlines.txt; do not edit.\n"
            f"export const AIRLINE_LOGOS=Object.freeze({json.dumps(sorted(logos))});\n"
            "// Null prototype: feed-supplied callsign prefixes never resolve inherited keys.\n"
            "export const AIRLINE_DESIGNATORS=Object.freeze(Object.assign(Object.create(null),"
            f"{json.dumps(designators)}));\n")


def main():
    airlines = load_airlines()
    offline = "--offline" in sys.argv[1:]
    LOGOS.mkdir(exist_ok=True)
    found, missing = [], []
    for code in airlines:
        data = None if offline else fetch(code)
        if data is not None:
            (LOGOS/f"{code}.png").write_bytes(data)
        if (LOGOS/f"{code}.png").exists():
            found.append(code)
        else:
            missing.append(code)
    for stale in LOGOS.glob("*.png"):
        if stale.stem not in found:
            stale.unlink()
    MODULE.write_text(render(found, airlines), encoding="utf-8")
    print(f"Bundled {len(found)} logos; no logo for: {', '.join(missing) or 'none'}")


if __name__ == "__main__":
    main()
